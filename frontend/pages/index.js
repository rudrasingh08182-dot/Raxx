/* ── SPARKLES CANVAS ── */
function SparklesCanvas({ color = "#2fae82", count = 40, className = "" }) {
  const canvasRef = useRef(null);
  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    let raf;
    let w = (canvas.width = canvas.parentElement?.offsetWidth || 400);
    let h = (canvas.height = canvas.parentElement?.offsetHeight || 600);
    const onResize = () => {
      if (!canvas.parentElement) return;
      w = canvas.width = canvas.parentElement.offsetWidth;
      h = canvas.height = canvas.parentElement.offsetHeight;
    };
    window.addEventListener("resize", onResize);
    const dots = Array.from({ length: count }, () => ({
      x: Math.random() * w, y: Math.random() * h,
      r: Math.random() * 1.6 + 0.3, dx: (Math.random() - 0.5) * 0.3,
      dy: (Math.random() - 0.5) * 0.3, o: Math.random(),
      ds: Math.random() * 0.01 + 0.004, up: Math.random() > 0.5,
    }));
    const draw = () => {
      ctx.clearRect(0, 0, w, h);
      dots.forEach((p) => {
        p.x += p.dx; p.y += p.dy;
        if (p.x < 0) p.x = w; if (p.x > w) p.x = 0;
        if (p.y < 0) p.y = h; if (p.y > h) p.y = 0;
        if (p.up) { p.o += p.ds; if (p.o >= 1) p.up = false; }
        else { p.o -= p.ds; if (p.o <= 0.05) p.up = true; }
        ctx.fillStyle = color;
        ctx.globalAlpha = Math.max(0, Math.min(1, p.o)) * 0.8;
        ctx.beginPath(); ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2); ctx.fill();
      });
      raf = requestAnimationFrame(draw);
    };
    draw();
    return () => { window.removeEventListener("resize", onResize); cancelAnimationFrame(raf); };
  }, [color, count]);
  return <canvas ref={canvasRef} className={`block ${className}`} />;
}

/* ── FADE-IN ── */
function FadeIn({ children, delay = 0, className = "" }) {
  return (
    <motion.div
      initial={{ opacity: 0, y: 18 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-30px" }}
      transition={{ duration: 0.45, delay, ease: "easeOut" }}
      className={className}
    >
      {children}
    </motion.div>
  );
}

